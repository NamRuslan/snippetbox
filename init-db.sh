set -e

psql -v ON_ERROR_STOP=1 \
  --username "$POSTGRES_USER" \
  --dbname "$POSTGRES_DB" \
  -v app_user="$APP_DB_USER"\
  -v app_pass="$APP_DB_PASSWORD" <<-EOSQL

  CREATE TABLE IF NOT EXISTS public.sessions
  (
      token character(43) COLLATE pg_catalog."default" NOT NULL,
      data bytea NOT NULL,
      expiry timestamp(6) without time zone NOT NULL,
      CONSTRAINT sessions_pkey PRIMARY KEY (token)
  );

  CREATE TABLE IF NOT EXISTS public.snippets
  (
      id integer NOT NULL GENERATED ALWAYS AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
      title character varying(100) COLLATE pg_catalog."default" NOT NULL,
      content text COLLATE pg_catalog."default" NOT NULL,
      created timestamp without time zone NOT NULL,
      expires timestamp without time zone NOT NULL,
      CONSTRAINT snippets_pkey PRIMARY KEY (id)
  );

  CREATE TABLE IF NOT EXISTS public.users
  (
      id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
      name character varying(255) COLLATE pg_catalog."default" NOT NULL,
      email character varying(255) COLLATE pg_catalog."default" NOT NULL,
      hashed_password character(60) COLLATE pg_catalog."default" NOT NULL,
      created timestamp without time zone NOT NULL,
      CONSTRAINT users_pkey PRIMARY KEY (id),
      CONSTRAINT users_uc_email UNIQUE (email)
  );

  CREATE INDEX idx_snippets_created ON snippets(created);
  CREATE INDEX sessions_expiry_idx ON sessions (expiry);

  CREATE USER :"app_user" WITH PASSWORD :'app_pass';
  GRANT CONNECT ON DATABASE snippetbox TO :"app_user";
  GRANT USAGE ON SCHEMA public TO :"app_user";
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE snippets, users, sessions TO :"app_user";
  GRANT USAGE, SELECT ON SEQUENCE snippets_id_seq, users_id_seq TO :"app_user";
EOSQL